import 'package:jig_protocol/jig_protocol.dart';

import 'scenario.dart';

/// Raised when a scenario contains a step an in-process test cannot replay.
final class JigExportException implements Exception {
  const JigExportException(this.message, {this.steps = const <int>[]});

  final String message;

  /// One-based positions of the offending steps.
  final List<int> steps;

  @override
  String toString() => message;
}

/// Writes a scenario as an `integration_test` Dart file.
///
/// The emitted test calls the same `JigActions` the CLI drives, so an exported check
/// fails for the same reasons the command does. A translation to `WidgetTester`
/// finders would be a second implementation of "act on an element", which is the
/// substitution this project argues against.
abstract final class JigExporter {
  /// Verbs with an in-process equivalent.
  ///
  /// The rest are diagnostics about a *session*: there is no session inside the test,
  /// so replaying them would mean asserting something that does not exist.
  static const Set<String> supported = <String>{
    'tap',
    'type',
    'clear',
    'adjust',
    'swipe',
    'scroll',
    'wait',
    'back',
    'state',
  };

  /// The steps an export would have to drop, one-based.
  static List<int> unsupportedSteps(JigScenario scenario) => <int>[
    for (final step in scenario.steps)
      if (!supported.contains(step.verb)) step.index + 1,
  ];

  static String export(
    JigScenario scenario, {
    required String entry,
  }) {
    final blocked = unsupportedSteps(scenario);
    if (blocked.isNotEmpty) {
      final verbs = <String>{
        for (final step in scenario.steps)
          if (!supported.contains(step.verb)) step.verb,
      };
      throw JigExportException(
        'Cannot export: step${blocked.length == 1 ? '' : 's'} '
        '${blocked.join(', ')} '
        '${blocked.length == 1 ? 'uses' : 'use'} ${verbs.join(', ')}, which '
        '${verbs.length == 1 ? 'is a diagnostic with' : 'are diagnostics with'} no '
        'in-process equivalent. Remove ${verbs.length == 1 ? 'it' : 'them'} or run '
        'the scenario with `jig run`.',
        steps: blocked,
      );
    }

    final buffer = StringBuffer()
      ..writeln('// GENERATED by `jig export`. Do not edit; regenerate instead.')
      ..writeln('// Scenario: ${scenario.name}')
      ..writeln('//')
      ..writeln('// Runs the same verbs the CLI drives, in-process, so it fails for')
      ..writeln('// the reasons `jig run` fails rather than for new ones.')
      ..writeln()
      ..writeln("import 'dart:async';")
      ..writeln()
      ..writeln("import 'package:flutter_test/flutter_test.dart';")
      ..writeln("import 'package:integration_test/integration_test.dart';")
      ..writeln("import 'package:jig_flutter/jig_flutter.dart';")
      ..writeln("import 'package:jig_protocol/jig_protocol.dart';")
      ..writeln()
      ..writeln("import '$entry' as app;")
      ..writeln()
      ..writeln('void main() {')
      ..writeln('  IntegrationTestWidgetsFlutterBinding.ensureInitialized();')
      ..writeln()
      ..writeln("  testWidgets('${_escape(scenario.name)}', (")
      ..writeln('    WidgetTester tester,')
      ..writeln('  ) async {')
      ..writeln('    await app.main();')
      ..writeln('    await tester.pumpAndSettle();')
      ..writeln()
      ..writeln('    final handle = tester.ensureSemantics();')
      ..writeln('    try {');

    for (final step in scenario.steps) {
      buffer
        ..writeln()
        ..writeln('      // step ${step.index + 1}: ${step.verb}');
      for (final line in _step(step)) {
        buffer.writeln('      $line');
      }
    }

    buffer
      ..writeln('    } finally {')
      ..writeln('      // The app installed its own semantics handle in main(); the test owns')
      ..writeln('      // that lifecycle now, and leaving it outstanding fails the run.')
      ..writeln('      Jig.uninstall();')
      ..writeln('      handle.dispose();')
      ..writeln('    }')
      ..writeln('  });')
      ..writeln('}')
      ..writeln()
      ..writeln(_helpers);

    return buffer.toString();
  }

  /// One step, as the lines that run it.
  static List<String> _step(JigScenarioStep step) {
    switch (step.verb) {
      case 'tap':
        final ref = step.ref;
        if (ref != null) {
          return <String>["JigActions.tapRef('${_escape(ref)}');"];
        }
        return <String>[
          'await _drive(tester, JigActions.tap(${_selector(step)}));',
        ];

      case 'type':
        return <String>[
          'await _drive(',
          '  tester,',
          '  JigActions.typeText(',
          '    ${_selector(step)},',
          "    '${_escape(step.value ?? '')}',",
          '  ),',
          ');',
        ];

      case 'clear':
        return <String>[
          'await _drive(tester, JigActions.clearText(${_selector(step)}));',
        ];

      case 'adjust':
        return <String>[
          'await _drive(',
          '  tester,',
          '  JigActions.adjust(',
          '    ${_selector(step)},',
          "    increase: ${step.direction != 'down'},",
          '    times: ${step.times ?? 1},',
          '  ),',
          ');',
        ];

      case 'swipe':
        return <String>[
          'await _drive(',
          '  tester,',
          '  JigActions.swipe(',
          '    ${_selector(step)},',
          '    direction: JigSwipeDirection.${step.direction ?? 'left'},',
          '  ),',
          ');',
        ];

      case 'scroll':
        return <String>[
          'await _drive(',
          '  tester,',
          '  JigActions.scrollUntil(',
          '    ${_selector(step)},',
          '    horizontal: ${step.horizontal},',
          '    steps: ${step.steps},',
          if (step.within != null) "    within: '${_escape(step.within!)}',",
          '  ),',
          ');',
        ];

      case 'wait':
        final predicate =
            'JigActions.isPresent(${_selector(step)})';
        return <String>[
          'await _pumpUntil(',
          '  tester,',
          '  () => ${step.present ? predicate : '!($predicate)'},',
          '  maxFrames: ${(step.timeout.inMilliseconds / 16).ceil()},',
          ');',
        ];

      case 'back':
        return <String>['await _drive(tester, JigActions.back());'];

      case 'state':
        if (step.expect.isEmpty) {
          return <String>[
            '// reads state only; nothing to assert',
            'JigStateRegistry.snapshot();',
          ];
        }
        final names = step.expect.keys.map((String k) => "'${_escape(k)}'").join(', ');
        final lines = <String>[
          'final snapshot = JigStateRegistry.snapshot(',
          '  only: <String>[$names],',
          ');',
        ];
        for (final expected in step.expect.entries) {
          lines.add(
            "expect(snapshot['${_escape(expected.key)}']?.value, "
            '${_literal(expected.value)});',
          );
        }
        return lines;
    }
    return const <String>[];
  }

  /// A selector in the flat form the runtime constructors take.
  static String _selector(JigScenarioStep step) {
    final selector = step.selector;
    if (selector == null) {
      return 'JigSelector.text(\'\')';
    }
    return switch (selector.kind) {
      SelectorKind.key => "JigSelector.key('${_escape(selector.value)}')",
      SelectorKind.semantic =>
        "JigSelector.semantic('${_escape(selector.value)}', "
            'exact: ${selector.exact})',
      SelectorKind.widgetType =>
        "JigSelector.widgetType('${_escape(selector.value)}', "
            'index: ${selector.index})',
      SelectorKind.text => "JigSelector.text('${_escape(selector.value)}')",
    };
  }

  /// A Dart literal for an expected value, without importing `json`.
  static String _literal(Object? value) {
    if (value == null) {
      return 'null';
    }
    if (value is num || value is bool) {
      return '$value';
    }
    return "'${_escape('$value')}'";
  }

  static String _escape(String raw) =>
      raw.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll('\n', r'\n');

  /// The helpers the file carries so it compiles wherever it is dropped.
  ///
  /// `JigActions` waits on `SchedulerBinding.endOfFrame`, and a frame only happens
  /// when a test pumps one, so awaiting a verb directly deadlocks. This is the same
  /// loop `apps/fixture/test/support` uses, inlined rather than imported.
  static const String _helpers = '''
/// Pumps frames while [action] runs.
///
/// Takes a `FutureOr` because the verbs are not uniform: `tap` answers immediately
/// while `typeText` and `swipe` wait for frames, and a generated file should not have
/// to know which is which.
Future<T> _drive<T>(
  WidgetTester tester,
  FutureOr<T> action, {
  int maxFrames = 1200,
}) async {
  var done = false;
  Object? failure;
  late T result;
  unawaited(
    Future<T>.value(action).then(
      (T value) {
        result = value;
        done = true;
      },
      onError: (Object error) {
        failure = error;
        done = true;
      },
    ),
  );
  await _pumpUntil(tester, () => done, maxFrames: maxFrames);
  final error = failure;
  if (error != null) {
    throw error;
  }
  return result;
}

/// Pumps until [isDone] holds, or fails on the frame budget.
Future<void> _pumpUntil(
  WidgetTester tester,
  bool Function() isDone, {
  required int maxFrames,
}) async {
  for (var frame = 0; frame < maxFrames; frame++) {
    if (isDone()) {
      return;
    }
    await tester.pump(const Duration(milliseconds: 16));
  }
  fail('The condition never became true within \$maxFrames frames.');
}
''';
}
